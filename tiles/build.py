def turned(im, quarters):
	return im.rotate(-90 * quarters)  # clockwise


def arrows(pack):
	east = paint(ARROW)
	northeast = pack.crop((41 * T, 5 * T, 42 * T, 6 * T))
	return [turned(east, 3), northeast, east, turned(northeast, 1), turned(east, 1), turned(northeast, 2), turned(east, 2), turned(northeast, 3)]


def paint(text):
	im = Image.new("RGBA", (T, T), (0, 0, 0, 0))
	rows = text.strip("\n").split("\n")
	assert len(rows) == T, "%d rows" % len(rows)
	for y, row in enumerate(rows):
		assert len(row) == T, "row %d is %d wide: %r" % (y, len(row), row)
		for x, ch in enumerate(row):
			if ch == "#":
				im.putpixel((x, y), (255, 255, 255, 255))
	return im


def main():
	cache = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, ".packs")
	os.makedirs(cache, exist_ok=True)
	path = os.path.join(cache, "kenney_1-bit-pack.zip")
	if not os.path.exists(path):
		print("downloading", PACK)
		urllib.request.urlretrieve(PACK, path)
	with zipfile.ZipFile(path) as z:
		pack = Image.open(io.BytesIO(z.read(SHEET))).convert("RGBA")
	custom = [paint(art) for art in CUSTOM] + arrows(pack) + [paint(FIRE)] + [paint(art) for art in FLOOR] + [paint(PLATE)]
	cols = pack.width // T
	rows = pack.height // T + (len(custom) + cols - 1) // cols
	sheet = Image.new("RGBA", (cols * T, rows * T), (0, 0, 0, 0))
	sheet.paste(pack, (0, 0))
	for i, im in enumerate(custom):
		sheet.paste(im, ((i % cols) * T, (pack.height // T + i // cols) * T))
	sheet.save(os.path.join(HERE, "tiles.png"))

	# The guide: every square 3x, with its column,row above it.
	S, PAD = 3, 12
	guide = Image.new("RGBA", (cols * (T * S + 2), rows * (T * S + PAD)), (40, 40, 60, 255))
	d = ImageDraw.Draw(guide)
	for r in range(rows):
		for c in range(cols):
			im = sheet.crop((c * T, r * T, c * T + T, r * T + T)).resize((T * S, T * S), Image.NEAREST)
			x, y = c * (T * S + 2), r * (T * S + PAD)
			guide.paste(im, (x, y + PAD), im)
			d.text((x + 1, y), "%d,%d" % (c, r), fill=(255, 230, 90, 255))
	guide.save(os.path.join(HERE, "guide.png"))
	print("wrote tiles.png (%dx%d, %d squares) and guide.png" % (sheet.width, sheet.height, cols * rows))


if __name__ == "__main__":
	main()

"""Builds tiles.png (the sheet Zot draws with) and guide.png (the same sheet,
blown up and labeled with each square's column,row so you can pick sprites).

The sheet is Kenney's "1-Bit Pack" (CC0): white shapes on a transparent
background, 49 squares wide and 22 tall, 16 pixels each, plus the squares
drawn below in CUSTOM, which go in row 22 and onward. Zot colors each
square when it draws it, with the color of whatever it stands for.

    python3 tiles/build.py            # downloads the pack, then builds

To add a square of your own, draw it in CUSTOM: 16 lines of 16 letters,
# for white and . for see-through. The first one is column 0 of row 22,
the next column 1, and so on (49 to a row). After CUSTOM come the eight
arrows from ARROWS, then the campfire's second frame from FIRE, then the
dungeon floors from FLOOR, then the pushed plate from PLATE. Run the script
and point at a square with tile: [column, row].

Needs Pillow (pip install pillow)."""

